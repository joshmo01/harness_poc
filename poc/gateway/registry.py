"""Agent & MCP registry: the source of truth for what may exist.

`registry.yaml` lists registered agents, MCP servers and tools, each tool with
its risk tier, owner, allowed agents and a pinned SHA-256 hash of its
description + input schema. Only CI changes this file (see README).

Run `python -m poc.gateway.registry --pin` to (re)generate it from the stub
servers' approved tool definitions.
"""
import argparse
import hashlib
import json

import yaml

from poc.common.config import REGISTRY_PATH

TIERS = {
    "los.get_case_summary": "read", "los.list_documents": "read", "los.get_bank_transactions": "read",
    "los.approve_sanction": "money-moving", "bureau.get_bureau_summary": "read",
    "lms.get_repayment_history": "read", "collections.get_dpd_summary": "read",
    "collections.log_promise_to_pay": "write", "core.assess_case": "read",
}
OWNERS = {"los": "LOS platform team", "bureau": "Credit data team", "lms": "LMS team",
          "collections": "Collections platform team", "core": "Credit risk engineering"}


def tool_hash(tool: dict) -> str:
    """Hash of everything the model reads about a tool."""
    canonical = json.dumps({"name": tool["name"], "description": tool["description"],
                            "inputSchema": tool["inputSchema"]}, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(canonical.encode()).hexdigest()


def load() -> dict:
    with open(REGISTRY_PATH) as f:
        return yaml.safe_load(f)


def pin() -> None:
    from poc.stubs.servers import TOOLS  # approved definitions (not tampered)

    registry = {
        "version": 1,
        "agents": {
            "uw-agent": {"owner": "Credit risk engineering", "status": "active",
                         "description": "Underwriting and collections assistant"},
            "lending-bff": {"owner": "Digital lending team", "status": "active",
                            "description": "Backend-for-frontend: fills A2UI bindings, handles approvals"},
        },
        "servers": {s: {"owner": OWNERS[s], "version": "1.0.0", "status": "active"} for s in TOOLS},
        "tools": {},
    }
    for server, tools in TOOLS.items():
        for t in tools:
            fq = f"{server}.{t['name']}"
            registry["tools"][fq] = {
                "server": server, "tier": TIERS[fq], "owner": OWNERS[server], "status": "active",
                # Money-moving tools are never granted to an agent; only the BFF calls them,
                # and only with a human approval token.
                "allowed_agents": ["lending-bff"] if TIERS[fq] == "money-moving" else ["uw-agent", "lending-bff"],
                "pinned_sha256": tool_hash(t),
            }
    with open(REGISTRY_PATH, "w") as f:
        f.write("# Generated by `python -m poc.gateway.registry --pin`; changes go through CI review.\n")
        yaml.safe_dump(registry, f, sort_keys=False)
    print(f"Pinned {len(registry['tools'])} tools to {REGISTRY_PATH}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--pin", action="store_true")
    if ap.parse_args().pin:
        pin()
